import type { Writable } from 'stream';
import ExcelJS from 'exceljs';
import type { ReportDefinition, ReportSummaryItem } from '../types';
import { sanitizeFormulaInjection } from '../helpers';

export interface XlsxExportOptions {
  report: ReportDefinition;
  stream: AsyncIterable<Record<string, unknown>[]>;
  output: Writable;
  summary?: ReportSummaryItem[];
  filters?: Record<string, unknown>;
  generatedBy?: string;
}

export async function exportReportToXlsx(
  options: XlsxExportOptions,
): Promise<{ rowCount: number }> {
  const { report, stream, output, summary = [], filters = {}, generatedBy = 'System' } = options;

  const workbook = new ExcelJS.stream.xlsx.WorkbookWriter({
    stream: output,
    useStyles: true,
    useSharedStrings: true,
  });

  const sheet = workbook.addWorksheet(report.title.slice(0, 31), {
    views: [{ state: 'frozen', xSplit: 0, ySplit: 1 }],
  });

  // Setup columns
  sheet.columns = report.columns.map((c) => ({
    header: c.label,
    key: c.key,
    width: Math.max(c.label.length + 4, 15),
  }));

  // Style header row
  const headerRow = sheet.getRow(1);
  headerRow.height = 24;
  headerRow.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  headerRow.fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF1E293B' }, // Dark slate
  };
  headerRow.alignment = { vertical: 'middle', horizontal: 'left' };
  headerRow.commit();

  let rowCount = 0;

  for await (const chunk of stream) {
    for (const item of chunk) {
      rowCount++;
      const rowData: Record<string, unknown> = {};

      for (const col of report.columns) {
        let val = item[col.key];
        if (typeof val === 'string') {
          val = sanitizeFormulaInjection(val);
        }
        rowData[col.key] = val !== undefined && val !== null ? val : '';
      }

      const row = sheet.addRow(rowData);
      row.commit();
    }
  }

  sheet.commit();

  // Summary and metadata worksheet
  const summarySheet = workbook.addWorksheet('Report Information');
  summarySheet.columns = [
    { header: 'Property', key: 'property', width: 25 },
    { header: 'Value', key: 'value', width: 45 },
  ];

  const sumHeader = summarySheet.getRow(1);
  sumHeader.font = { bold: true, color: { argb: 'FFFFFFFF' } };
  sumHeader.fill = {
    type: 'pattern',
    pattern: 'solid',
    fgColor: { argb: 'FF334155' },
  };
  sumHeader.commit();

  summarySheet.addRow({ property: 'Report Title', value: report.title }).commit();
  summarySheet.addRow({ property: 'Report Key', value: report.key }).commit();
  summarySheet.addRow({ property: 'Generated At', value: new Date().toISOString() }).commit();
  summarySheet.addRow({ property: 'Generated By', value: generatedBy }).commit();
  summarySheet.addRow({ property: 'Total Rows Exported', value: rowCount }).commit();
  summarySheet.addRow({ property: 'Applied Filters', value: JSON.stringify(filters) }).commit();

  if (summary.length > 0) {
    summarySheet.addRow({ property: '--- KPI SUMMARY ---', value: '' }).commit();
    for (const s of summary) {
      summarySheet.addRow({ property: s.label, value: s.value }).commit();
    }
  }

  summarySheet.commit();

  await workbook.commit();

  return { rowCount };
}
